"use client";

import Image from "next/image";
import { useState } from "react";
import { ShareIcon } from "@/app/dashboard/icons";
import type { Dictionary } from "@/lib/i18n/dictionaries/types";
import { format } from "@/lib/i18n/format";
import { CopyIcon, EllipsisIcon } from "./icons";
import {
  ActionItemContent,
  actionItemClass,
  GroupedList,
  IconTile,
  RowBody,
  RowText,
  type ActionVariant,
} from "./ios";
import { Sheet } from "@/components/sheet";
import { copyText } from "@/components/toast";

// The Share action: opens a sheet with a scannable QR of this profile (so
// someone can show their card to a person without NFC), Copy link, and the
// system share sheet where the browser has one. The QR SVG is generated on
// the server (src/app/t/[tag_id]/page.tsx) so no QR library ships to the client.
export function ShareAction({
  variant,
  profileUrl,
  qrSvg,
  name,
  avatarUrl,
  dict,
}: {
  variant: ActionVariant;
  profileUrl: string;
  qrSvg: string;
  name: string;
  avatarUrl: string | null;
  dict: Dictionary["profile"];
}) {
  const [open, setOpen] = useState(false);
  const close = () => setOpen(false);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        aria-haspopup="dialog"
        className={actionItemClass(variant)}
      >
        <ActionItemContent
          variant={variant}
          icon={<ShareIcon className="h-5 w-5" />}
          label={dict.share}
        />
      </button>

      <Sheet open={open} onClose={close} title={dict.shareTitle} closeLabel={dict.close}>
        <div className="flex flex-col items-center pb-5 pt-1 text-center">
          <div className="relative w-60 rounded-[24px] bg-white p-3.5 shadow-[0_8px_30px_-12px_rgba(0,0,0,0.3)] ring-1 ring-black/5">
            {qrSvg ? (
              <div
                role="img"
                aria-label={format(dict.scanToOpen, { name })}
                className="[&>svg]:block [&>svg]:h-auto [&>svg]:w-full"
                // Server-generated by the `qrcode` package from our own URL.
                dangerouslySetInnerHTML={{ __html: qrSvg }}
              />
            ) : (
              <div className="aspect-square w-full rounded-xl bg-slate-100" />
            )}
            {/* Error correction "H" leaves room for a centre badge. */}
            <span className="absolute left-1/2 top-1/2 grid h-12 w-12 -translate-x-1/2 -translate-y-1/2 place-items-center overflow-hidden rounded-full bg-brand-900 text-lg font-bold text-white ring-4 ring-white">
              {avatarUrl ? (
                <Image src={avatarUrl} alt="" width={48} height={48} className="h-full w-full object-cover" />
              ) : (
                name.slice(0, 1).toUpperCase()
              )}
            </span>
          </div>
          <p className="mt-4 text-[15px] font-semibold">{format(dict.scanToOpen, { name })}</p>
          <p className="mt-0.5 max-w-full truncate text-[13px] text-ios-label-2">
            {profileUrl.replace(/^https?:\/\//, "")}
          </p>
        </div>

        <GroupedList>
          <button
            type="button"
            onClick={() => copyText(profileUrl, dict.linkCopied)}
            className="ios-row group/row flex w-full items-center bg-ios-surface pl-4"
          >
            <IconTile className="bg-ios-tint text-white">
              <CopyIcon className="h-4 w-4" />
            </IconTile>
            <RowBody className="pr-4">
              <RowText title={dict.copyLink} />
            </RowBody>
          </button>
          {typeof navigator !== "undefined" && "share" in navigator && (
            <button
              type="button"
              onClick={async () => {
                try {
                  await navigator.share({ url: profileUrl, title: name });
                } catch {
                  // Cancelled the system sheet — nothing to do.
                }
              }}
              className="ios-row group/row flex w-full items-center bg-ios-surface pl-4"
            >
              <IconTile className="bg-ios-label-2 text-white">
                <EllipsisIcon className="h-4 w-4" />
              </IconTile>
              <RowBody className="pr-4">
                <RowText title={dict.moreOptions} />
              </RowBody>
            </button>
          )}
        </GroupedList>
      </Sheet>
    </>
  );
}
